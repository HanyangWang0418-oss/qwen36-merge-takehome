#!/usr/bin/env python
"""Regenerate the model table in models/README.md from data/manifests/hf_models.json and
data/manifests/merge_recipes/*.json (between the AUTO markers)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
m = json.loads((ROOT / "data/manifests/hf_models.json").read_text())
rec_dir = ROOT / "data/manifests/merge_recipes"
ROLE = {"e1_code_repair": "expert: code repair (SWE-bench Pro)", "e2_terminal_agent": "expert: terminal / research agent (TB2, ASI)",
        "e3_reasoning": "expert: reasoning (HLE)", "e1_code_repair_r64": "control: rank 64 vs 32", "e2a_terminal_only": "control: 4-expert split (pure terminal)",
        "e2b_terminal_swe": "control: 4-expert split (SWE-in-terminal)"}
rows = ["| name | HF repo | revision | kind | size | recipe / notes |", "|---|---|---|---|---|---|"]
for name, v in m.items():
    rec_p = rec_dir / f"{name}.json"
    if rec_p.exists():
        r = json.loads(rec_p.read_text())
        lams = sorted({e["lambda"] for e in r["experts"]}); dens = r.get("density", 1.0)
        exps = ", ".join(Path(e["path"]).name for e in r["experts"])
        err = r.get("svd_rel_error", {}).get("mean", 0.0)
        kind = f"merged LoRA r{r['out_rank']} ({r['method']})"
        note = f"λ={lams}, density={dens}; experts: {exps}" + (f"; SVD rel. err mean {err:.2f}" if err else "; exact")
        size = f"{v.get('adapter_bytes', 0) / 1e9:.2f} GB" if v.get("adapter_bytes") else "6.74 GB" if r["out_rank"] == 96 else ""
    else:
        kind = "LoRA r64 α32" if "r64" in name else "LoRA r32 α32"
        note = ROLE.get(name, "")
        size = f"{v.get('adapter_bytes', 0) / 1e9:.2f} GB" if v.get("adapter_bytes") else "2.24 GB"
    rows.append(f"| {name} | https://huggingface.co/{v['repo_id']} | `{v['revision']}` | {kind} | {size} | {note} |")
table = "\n".join(rows)
p = ROOT / "models/README.md"; s = p.read_text()
start, end = "<!-- AUTO:models -->", "<!-- /AUTO:models -->"
block = f"{start}\n_Generated by `scripts/render_models_readme.py` from `data/manifests/hf_models.json`._\n\n{table}\n{end}"
if start in s:
    s = s[: s.index(start)] + block + s[s.index(end) + len(end):]
else:
    # replace the hand-written table (from the first '| name |' header to the blank line after it)
    i = s.index("| name |"); j = s.index("\n\n", i)
    s = s[:i] + block + s[j:]
p.write_text(s)
print(f"{len(m)} models written to models/README.md")
